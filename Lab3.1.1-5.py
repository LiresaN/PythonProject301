# Задача 2: Удаление дубликатов
# Дан список чисел с повторениями: numbers = [1, 2, 3, 2, 1, 4, 5, 4, 6, 7, 8, 7, 9].
# Создайте новый список без дубликатов, сохранив первоначальный порядок элементов. Выведите:
#   Исходный список
#   Новый список без дубликатов
#   Количество удаленных дубликатов
#
numbers = [1, 2, 3, 2, 1, 1, 1, 4, 5, 4, 6, 7, 8, 7, 9]
numbers_check = 0
numbers_new = numbers.copy()

for i in numbers_new:
    if numbers_new.count(i) > 1:
        numbers_check += 1
        numbers_new.remove(i)

print(numbers)
print(numbers_new)
print(numbers_check)


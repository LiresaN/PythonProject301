# Задача 4: Матрица и операции с ней
# Создайте матрицу (список списков) размером 3x3 и заполните её числами от 1 до 9 по порядку. Выведите:
#   Получившуюся матрицу в виде таблицы
#   Сумму элементов на главной диагонали (числа с индексами [0][0], [1][1], [2][2])
#   Максимальный элемент в каждой строке
#
matrix = [[elem1 for elem1 in range(1,4)],[elem2 for elem2 in range(4,7)],[elem2 for elem2 in range(7,10)]]
print(matrix)
print(sum([matrix[i][k] for i in range(0,3) for k in range(0,3) if i == k]))
print([max(matrix[i]) for i in range(0,3)])


